export function clearPrivateSession(setters, blank, staffMode) {
  const clean = {
    member: null,
    selected: null,
    preview: null,
    history: null,
    receipt: null,
    accessMembers: [],
    code: '',
    codeSent: false,
    properties: [],
    inquiries: [],
    saved: [],
    message: '',
    view: staffMode ? 'Property log' : 'Inventory',
    draft: structuredClone(blank),
    editing: false,
    dirty: false,
    file: null,
    rights: '',
    alt: '',
    confirmation: null,
    search: '',
    filter: 'All',
    assetFilter: 'All',
    maxPrice: '',
    packetTab: 'Overview',
    proposed: '',
    timing: '',
    requestKey: crypto.randomUUID(),
    investorEmail: '',
    contactId: '',
  };
  for (const [key, set] of Object.entries(setters)) set(clean[key]);
}
